/** One open-source component and its licence, as the AboutLibraries plugin collected it at build time. */
data class LicenseEntry(val name: String, val version: String?, val licenses: String, val text: String)

/** Reads `res/raw/aboutlibraries.json` (generated by the AboutLibraries Gradle plugin) plus the bundled font. */
fun loadLicenses(context: Context): List<LicenseEntry> {
    val json = context.resources.openRawResource(R.raw.aboutlibraries).bufferedReader().use { it.readText() }
    val libs = Libs.Builder().withJson(json).build()
    val fromGradle = libs.libraries.map { lib ->
        LicenseEntry(
            name = lib.name,
            version = lib.artifactVersion,
            licenses = lib.licenses.joinToString { it.spdxId ?: it.name }.ifEmpty { "See project" },
            text = lib.licenses.joinToString("\n\n") { l -> l.licenseContent?.takeIf { it.isNotBlank() } ?: (l.name + (l.url?.let { "\n$it" } ?: "")) }
                .ifEmpty { lib.website ?: "" },
        )
    }
    // Inter is a font file, not a Gradle dependency, so the plugin can't see it.
    val inter = LicenseEntry("Inter (font)", "4", "OFL-1.1", "Inter is licensed under the SIL Open Font License, Version 1.1.\nhttps://openfontlicense.org\nCopyright 2016 The Inter Project Authors (https://github.com/rsms/inter)")
    return (fromGradle + inter).sortedBy { it.name.lowercase() }
}

@Composable
fun LicensesScreen(nav: AppNavigator) {
    val context = LocalContext.current
    val entries by produceState<List<LicenseEntry>?>(null) {
        value = withContext(Dispatchers.IO) { runCatching { loadLicenses(context) }.getOrDefault(emptyList()) }
    }
    var open by remember { mutableStateOf<LicenseEntry?>(null) }
    val first = remember { FocusRequester() }
    BackHandler { nav.back() }
    LaunchedEffect(entries?.isNotEmpty()) { if (entries?.isNotEmpty() == true) runCatching { first.requestFocus() } }

    Column(Modifier.fillMaxSize().background(Emberfin.colors.background)) {
        Text(
            "Open-source licences", style = EmberfinType.headline, color = Emberfin.colors.onBackground,
            modifier = Modifier.padding(start = Dimens.ScreenPadding, top = 36.dp),
        )
        Text(
            "Emberfin is Apache-2.0 licensed and built on these projects.", style = EmberfinType.body, color = Emberfin.colors.muted,
            modifier = Modifier.padding(start = Dimens.ScreenPadding, top = 4.dp, bottom = 6.dp),
        )
        LazyColumn(
            contentPadding = PaddingValues(start = Dimens.ScreenPadding, end = Dimens.ScreenPadding, top = 6.dp, bottom = 60.dp),
            modifier = Modifier.widthIn(max = 720.dp),
        ) {
            itemsIndexed(entries.orEmpty(), key = { i, e -> "$i/${e.name}" }) { i, e ->
                SettingRow(
                    label = e.name + (e.version?.let { "  $it" } ?: ""),
                    value = e.licenses,
                    onClick = { open = e },
                    modifier = if (i == 0) Modifier.focusRequester(first) else Modifier,
                )
            }
        }
    }
    open?.let { LicenseDialog(it) { open = null } }
}

/** The licence text; Up/Down scroll it. */
@Composable
private fun LicenseDialog(entry: LicenseEntry, onDismiss: () -> Unit) {
    val scroll = rememberScrollState()
    val scope = rememberCoroutineScope()
    val focus = remember { FocusRequester() }
    Dialog(onDismissRequest = onDismiss) {
        Column(
            Modifier
                .width(640.dp)
                .heightIn(max = 440.dp)
                .background(Emberfin.colors.surface, RoundedCornerShape(10.dp))
                .padding(22.dp)
                .focusRequester(focus)
                .focusable()
                .onKeyEvent { ev ->
                    if (ev.type != KeyEventType.KeyDown) return@onKeyEvent false
                    when (ev.nativeKeyEvent.keyCode) {
                        AndroidKey.KEYCODE_DPAD_DOWN -> { scope.launch { scroll.animateScrollBy(220f) }; true }
                        AndroidKey.KEYCODE_DPAD_UP -> { scope.launch { scroll.animateScrollBy(-220f) }; true }
                        AndroidKey.KEYCODE_DPAD_CENTER, AndroidKey.KEYCODE_ENTER -> { onDismiss(); true }
                        else -> false
                    }
                },
        ) {
            Text(entry.name, style = EmberfinType.title, color = Emberfin.colors.onBackground)
            Text(entry.licenses, style = EmberfinType.meta, color = Emberfin.colors.accent)
            Spacer(Modifier.height(10.dp))
            Column(Modifier.verticalScroll(scroll)) {
                Text(entry.text, style = EmberfinType.label, color = Emberfin.colors.muted)
            }
        }
    }
    LaunchedEffect(Unit) { runCatching { focus.requestFocus() } }
}
